export const API_ENDPOINTS = Object.freeze(endpoints.map((endpoint) => Object.freeze(endpoint)));

export const API_ENDPOINT_BY_CODE = Object.freeze(
  Object.fromEntries(API_ENDPOINTS.map((endpoint) => [endpoint.code, endpoint])),
);

/** Chỉ các endpoint thực sự được sinh route (bỏ alias trùng path+method). */
export const PRIMARY_API_ENDPOINTS = Object.freeze(
  API_ENDPOINTS.filter((endpoint) => !endpoint.aliasOf),
);

export const API_ENDPOINT_COUNT = API_ENDPOINTS.length;

export const API_ENDPOINT_COUNTS_BY_MODULE = Object.freeze(
  API_ENDPOINTS.reduce((acc, endpoint) => {
    acc[endpoint.module] = (acc[endpoint.module] || 0) + 1;
    return acc;
  }, {}),
);

export function getApiEndpoint(code) {
  return API_ENDPOINT_BY_CODE[code] ?? null;
}

export function getEndpointsByModule(moduleCode) {
  return API_ENDPOINTS.filter((endpoint) => endpoint.module === moduleCode);
}

export function getPrimaryEndpointsByModule(moduleCode) {
  return PRIMARY_API_ENDPOINTS.filter((endpoint) => endpoint.module === moduleCode);
}

export function getEndpointsByPath(path) {
  return API_ENDPOINTS.filter((endpoint) => endpoint.path === path);
}

export function isPublicEndpoint(endpoint) {
  return endpoint.access === 'public' || endpoint.access === 'optional';
}
