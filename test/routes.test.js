import { readFile, stat } from 'node:fs/promises';
import path from 'node:path';
import { describe, expect, it } from 'vitest';
import { API_ENDPOINTS, PRIMARY_API_ENDPOINTS } from '@/shared/api-endpoints.js';

const ROOT = process.cwd();

function routeFile(apiPath) {
  return path.join(ROOT, 'src', 'app', ...apiPath.split('/').filter(Boolean), 'route.js');
}

async function fileExists(filePath) {
  try {
    return (await stat(filePath)).isFile();
  } catch {
    return false;
  }
}

describe('generated API routes', () => {
  it('có route.js cho mọi endpoint chính', async () => {
    const missing = [];
    for (const endpoint of PRIMARY_API_ENDPOINTS) {
      if (!(await fileExists(routeFile(endpoint.path)))) missing.push(endpoint.path);
    }
    expect(missing).toEqual([]);
  });

  it('route.js tham chiếu đúng mã API và method', async () => {
    for (const endpoint of PRIMARY_API_ENDPOINTS) {
      const content = await readFile(routeFile(endpoint.path), 'utf8');
      expect(content, endpoint.code).toContain('@generated by scripts/gen-routes.js');
      expect(content, endpoint.code).toContain(endpoint.code);
      expect(content, endpoint.code).toContain(`export const ${endpoint.method}`);
    }
  });

  it('không sinh route riêng cho endpoint alias', async () => {
    const aliases = API_ENDPOINTS.filter((endpoint) => endpoint.aliasOf);
    expect(aliases.length).toBeGreaterThan(0);
    for (const alias of aliases) {
      const content = await readFile(routeFile(alias.path), 'utf8');
      expect(content).not.toContain(`withApi('${alias.code}'`);
    }
  });
});
